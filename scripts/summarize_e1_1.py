#!/usr/bin/env python3
"""Aggregate the six E1.1 front-end probes into one table (ROADMAP E1.1).

Reads the harness output written by ``scripts/evaluate_e1_1.py``::

    <runs-root>/<frontend>/<checkpoint-stem>/metrics.json

and writes::

    <output-root>/summary.csv           one row per (frontend, split)
    <output-root>/per_attack_eer.csv    one row per (frontend, split, attack)
    <output-root>/RESULTS.md            human-readable comparison

Every row keeps the G4 metric contract: split, attack subset, threshold, and
sample count.  EER/AUC are threshold-free; the fixed-0.5 columns are a
descriptive operating point, not a tuned threshold.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "src"))

from spoof_detection.frontends import FRONTEND_ORDER  # noqa: E402

DEFAULT_RUNS_ROOT = "reports/phase1/e1_1_frontend/runs"
DEFAULT_OUTPUT_ROOT = "reports/phase1/e1_1_frontend"


def _checkpoint_stem(frontend: str) -> str:
    return f"resnet18_frozen_{frontend}"


def _float(value: object) -> float | None:
    try:
        return None if value is None else float(value)
    except (TypeError, ValueError):
        return None


def _load_metrics(path: Path) -> dict[str, object]:
    return json.loads(path.read_text(encoding="utf-8"))


def _summary_rows(
    frontend: str,
    metrics: dict[str, object],
    metrics_path: Path,
) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    thresholds = metrics.get("thresholds") or {}
    dev_threshold = thresholds.get("dev_eer")
    checkpoint = metrics.get("checkpoint") or {}
    for split, payload in (metrics.get("splits") or {}).items():
        summary = (payload or {}).get("metrics") or {}
        counts = summary.get("sample_counts") or {}
        fixed = (summary.get("threshold_metrics") or {}).get("fixed_0.5") or {}
        rows.append(
            {
                "frontend": frontend,
                "split": split,
                "attack_subset": (payload or {}).get("attack_subset"),
                "threshold_free_eer": _float(summary.get("eer")),
                "threshold_free_auc": _float(summary.get("auc")),
                "samples_total": counts.get("total"),
                "samples_bonafide": counts.get("bonafide"),
                "samples_spoof": counts.get("spoof"),
                "dev_eer_threshold": _float(dev_threshold),
                "fpr_at_0.5": _float(fixed.get("false_positive_rate")),
                "spoof_recall_at_0.5": _float(fixed.get("spoof_recall")),
                "checkpoint_sha256": checkpoint.get("sha256"),
                "metrics_path": str(metrics_path),
            }
        )
    return rows


def _per_attack_rows(
    frontend: str,
    metrics: dict[str, object],
) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for split, payload in (metrics.get("splits") or {}).items():
        summary = (payload or {}).get("metrics") or {}
        for attack_id, entry in (summary.get("per_attack") or {}).items():
            entry = entry or {}
            rows.append(
                {
                    "frontend": frontend,
                    "split": split,
                    "attack_id": attack_id,
                    "n_spoof": entry.get("n_spoof"),
                    "n_bonafide": entry.get("n_bonafide"),
                    "eer": _float(entry.get("eer")),
                    "auc": _float(entry.get("auc")),
                    "eer_threshold_descriptive": _float(
                        entry.get("eer_threshold_descriptive")
                    ),
                }
            )
    return rows


def _format_number(value: object, digits: int = 4) -> str:
    numeric = _float(value)
    return "n/a" if numeric is None else f"{numeric:.{digits}f}"


def _results_markdown(
    summary: pd.DataFrame,
    per_attack: pd.DataFrame,
    run_rows: list[dict[str, object]],
) -> str:
    lines: list[str] = []
    lines.append("# E1.1 front-end ablation — results\n")
    lines.append(
        "Generated by `scripts/summarize_e1_1.py` from the frozen E0.3 harness.\n"
    )
    lines.append(
        "**Metric contract.** EER/AUC are *threshold-free*. The "
        "`fpr_at_0.5` / `spoof_recall_at_0.5` columns are a descriptive fixed "
        "operating point, not a tuned threshold. The dev-selected EER "
        "threshold is recorded for provenance but is not the primary operating "
        "point in this table.\n"
    )

    missing = run_rows and all(not row["present"] for row in run_rows)
    if missing:
        lines.append(
            "> No `metrics.json` files were found; run "
            "`make e1-1-evaluate` first.\n"
        )

    lines.append("## Dev / eval summary\n")
    if summary.empty:
        lines.append("_No runs found._\n")
    else:
        header = (
            "| Front-end | Split | Attack subset | n (bonafide/spoof) | "
            "EER | AUC | FPR@0.5 | Spoof recall@0.5 |"
        )
        lines.append(header)
        lines.append("|---|---|---|---:|---:|---:|---:|---:|")
        for _, row in summary.sort_values(["frontend", "split"]).iterrows():
            lines.append(
                f"| `{row['frontend']}` | {row['split']} | {row['attack_subset']} | "
                f"{row['samples_total']} ({row['samples_bonafide']}/{row['samples_spoof']}) | "
                f"{_format_number(row['threshold_free_eer'])} | "
                f"{_format_number(row['threshold_free_auc'])} | "
                f"{_format_number(row['fpr_at_0.5'])} | "
                f"{_format_number(row['spoof_recall_at_0.5'])} |"
            )
        lines.append("")

    lines.append("## Per-attack EER\n")
    if per_attack.empty:
        lines.append("_No per-attack rows found._\n")
    else:
        attacks = sorted(per_attack["attack_id"].unique())
        frontends = sorted(per_attack["frontend"].unique())
        for split in sorted(per_attack["split"].unique()):
            lines.append(f"### {split}\n")
            lines.append(
                "| Front-end | " + " | ".join(attacks) + " |"
            )
            lines.append("|---|" + "---|" * len(attacks))
            subset = per_attack[per_attack["split"] == split]
            for frontend in frontends:
                values = []
                for attack in attacks:
                    match = subset[
                        (subset["frontend"] == frontend)
                        & (subset["attack_id"] == attack)
                    ]
                    values.append(
                        _format_number(match["eer"].iloc[0])
                        if not match.empty
                        else "n/a"
                    )
                lines.append(f"| `{frontend}` | " + " | ".join(values) + " |")
            lines.append("")

    lines.append("## Run inventory\n")
    lines.append("| Front-end | metrics.json | present |")
    lines.append("|---|---|:---:|")
    for row in run_rows:
        lines.append(
            f"| `{row['frontend']}` | `{row['metrics_path']}` | "
            f"{'yes' if row['present'] else 'no'} |"
        )
    lines.append("")
    return "\n".join(lines)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--runs-root",
        default=DEFAULT_RUNS_ROOT,
        help=f"evaluation output root (default: {DEFAULT_RUNS_ROOT})",
    )
    parser.add_argument(
        "--output-root",
        default=DEFAULT_OUTPUT_ROOT,
        help=f"report output root (default: {DEFAULT_OUTPUT_ROOT})",
    )
    parser.add_argument(
        "--frontends",
        nargs="+",
        choices=FRONTEND_ORDER,
        default=list(FRONTEND_ORDER),
        help="front-ends to summarize (default: all six)",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    repo_root = REPO_ROOT
    runs_root = Path(args.runs_root)
    if not runs_root.is_absolute():
        runs_root = (repo_root / runs_root).resolve()
    output_root = Path(args.output_root)
    if not output_root.is_absolute():
        output_root = (repo_root / output_root).resolve()
    output_root.mkdir(parents=True, exist_ok=True)

    summary_rows: list[dict[str, object]] = []
    attack_rows: list[dict[str, object]] = []
    run_rows: list[dict[str, object]] = []
    for frontend in args.frontends:
        metrics_path = (
            runs_root / frontend / _checkpoint_stem(frontend) / "metrics.json"
        )
        present = metrics_path.is_file()
        run_rows.append(
            {"frontend": frontend, "metrics_path": str(metrics_path), "present": present}
        )
        if not present:
            print(f"warning: missing {metrics_path}", file=sys.stderr)
            continue
        metrics = _load_metrics(metrics_path)
        summary_rows.extend(_summary_rows(frontend, metrics, metrics_path))
        attack_rows.extend(_per_attack_rows(frontend, metrics))

    summary = pd.DataFrame(summary_rows)
    per_attack = pd.DataFrame(attack_rows)

    summary_path = output_root / "summary.csv"
    per_attack_path = output_root / "per_attack_eer.csv"
    results_path = output_root / "RESULTS.md"

    if summary.empty:
        summary = pd.DataFrame(
            columns=[
                "frontend",
                "split",
                "attack_subset",
                "threshold_free_eer",
                "threshold_free_auc",
                "samples_total",
                "samples_bonafide",
                "samples_spoof",
                "dev_eer_threshold",
                "fpr_at_0.5",
                "spoof_recall_at_0.5",
                "checkpoint_sha256",
                "metrics_path",
            ]
        )
    if per_attack.empty:
        per_attack = pd.DataFrame(
            columns=[
                "frontend",
                "split",
                "attack_id",
                "n_spoof",
                "n_bonafide",
                "eer",
                "auc",
                "eer_threshold_descriptive",
            ]
        )

    summary.to_csv(summary_path, index=False)
    per_attack.to_csv(per_attack_path, index=False)
    results_path.write_text(
        _results_markdown(summary, per_attack, run_rows), encoding="utf-8"
    )

    print(f"wrote {summary_path}")
    print(f"wrote {per_attack_path}")
    print(f"wrote {results_path}")
    if not summary.empty:
        print("\n" + summary.to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
